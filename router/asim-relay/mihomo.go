// mihomo carries the ePDG UDP flow; the relay only renders this file and asks
// mihomo to reload. Keep the blast radius to the ePDG prefix.
const (
	mihomoDevice = "asim0"
	mihomoCIDR   = "31.94.76.0/24"
	mihomoProxy  = "ASIM-UK"
	// delayURL is what mihomo fetches through the proxy when the WebUI asks for
	// a latency number.
	delayURL = "http://www.gstatic.com/generate_204"
)

// renderMihomo returns a complete config.yaml for one upstream node. With
// enabled=false the TUN is off entirely, so ePDG goes out the router's own WAN.
func renderMihomo(n Node, enabled bool) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# generated by asim-relay; do not edit
mode: rule
log-level: info
ipv6: false
allow-lan: false
mixed-port: 0
external-controller: 127.0.0.1:9090
dns:
  enable: false
`)
	if enabled {
		fmt.Fprintf(&b, `tun:
  enable: true
  stack: system
  device: %s
  auto-route: true
  auto-detect-interface: true
  route-address: ["%s"]
  dns-hijack: []
`, mihomoDevice, mihomoCIDR)
	} else {
		b.WriteString("tun:\n  enable: false\n")
	}

	fmt.Fprintf(&b, "proxies:\n  - name: %s\n    type: %s\n    server: %s\n    port: %d\n",
		mihomoProxy, n.proto(), yamlStr(n.Host), n.Port)

	switch n.proto() {
	case "trojan", "hysteria2":
		fmt.Fprintf(&b, "    password: %s\n", yamlStr(n.Password))
		if n.SNI != "" {
			fmt.Fprintf(&b, "    sni: %s\n", yamlStr(n.SNI))
		}
		fmt.Fprintf(&b, "    skip-cert-verify: %v\n", n.skipVerify())
		if n.proto() == "trojan" {
			fmt.Fprintf(&b, "    udp: true\n")
		}
	case "vless":
		fmt.Fprintf(&b, "    uuid: %s\n", yamlStr(n.Password))
		fmt.Fprintf(&b, "    tls: true\n")
		if n.SNI != "" {
			fmt.Fprintf(&b, "    servername: %s\n", yamlStr(n.SNI))
		}
		fmt.Fprintf(&b, "    skip-cert-verify: %v\n", n.skipVerify())
		if n.Flow != "" {
			fmt.Fprintf(&b, "    flow: %s\n", yamlStr(n.Flow))
		}
		if n.Encryption != "" {
			fmt.Fprintf(&b, "    encryption: %s\n", yamlStr(n.Encryption))
		}
		fp := n.Fingerprint
		if fp == "" && n.RealityPublicKey != "" {
			fp = "chrome"
		}
		if fp != "" {
			fmt.Fprintf(&b, "    client-fingerprint: %s\n", yamlStr(fp))
		}
		switch n.network() {
		case "tcp":
		case "ws":
			fmt.Fprintf(&b, "    network: ws\n    ws-opts:\n      path: %s\n", yamlStr(n.Path))
			if n.HostHeader != "" {
				fmt.Fprintf(&b, "      headers:\n        Host: %s\n", yamlStr(n.HostHeader))
			}
		case "httpupgrade":
			fmt.Fprintf(&b, "    network: ws\n    ws-opts:\n      path: %s\n      v2ray-http-upgrade: true\n", yamlStr(n.Path))
		case "grpc":
			fmt.Fprintf(&b, "    network: grpc\n    grpc-opts:\n      grpc-service-name: %s\n", yamlStr(n.ServiceName))
		default:
			return nil, fmt.Errorf("mihomo 未接 vless %s，请改用 ws/grpc/tcp", n.network())
		}
		if n.RealityPublicKey != "" {
			fmt.Fprintf(&b, "    reality-opts:\n      public-key: %s\n", yamlStr(n.RealityPublicKey))
			if n.RealityShortID != "" {
				fmt.Fprintf(&b, "      short-id: %s\n", yamlStr(n.RealityShortID))
			}
		}
	default:
		return nil, fmt.Errorf("mihomo 未接协议 %s", n.proto())
	}

	b.WriteString("rules:\n")
	if enabled {
		fmt.Fprintf(&b, "  - IP-CIDR,%s,%s,no-resolve\n", mihomoCIDR, mihomoProxy)
	}
	b.WriteString("  - MATCH,DIRECT\n")
	return []byte(b.String()), nil
}

// yamlStr emits a plain scalar only when it is unambiguous; anything else is
// single-quoted with ” escapes.
func yamlStr(s string) string {
	if s == "" {
		return "''"
	}
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case r == '.', r == '_', r == '@', r == '/', r == '-':
		default:
			return "'" + strings.ReplaceAll(s, "'", "''") + "'"
		}
	}
	return s
}

// syncMihomo writes the config atomically and asks mihomo to reload it. A
// failed reload keeps the written file: mihomo still runs the old config, and
// the next successful reload or restart picks the new one up.
func syncMihomo(path, api, secret string, n Node, enabled bool) error {
	b, err := renderMihomo(n, enabled)
	if err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0600); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}

	body, _ := json.Marshal(map[string]string{"path": path})
	req, err := http.NewRequest(http.MethodPut, strings.TrimRight(api, "/")+"/configs?force=true", bytes.NewReader(body))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	if secret != "" {
		req.Header.Set("Authorization", "Bearer "+secret)
	}
	resp, err := (&http.Client{Timeout: 5 * time.Second}).Do(req)
	if err != nil {
		return fmt.Errorf("reload: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		msg, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
		return fmt.Errorf("reload: %s: %s", resp.Status, strings.TrimSpace(string(msg)))
	}
	return nil
}

type sessionInfo struct {
	Client   string `json:"client"`
	Dest     string `json:"dest"`
	LastSeen int    `json:"last_seen_s"`
}

// mihomoSessions reports the ePDG conversations mihomo currently carries, so
// the WebUI's status panel reflects the real data path.
func mihomoSessions(api, secret string) ([]sessionInfo, []string, error) {
	flows := []sessionInfo{}
	ips := []string{}
	var body struct {
		Connections []struct {
			Metadata struct {
				Network         string `json:"network"`
				SourceIP        string `json:"sourceIP"`
				SourcePort      string `json:"sourcePort"`
				DestinationIP   string `json:"destinationIP"`
				DestinationPort string `json:"destinationPort"`
			} `json:"metadata"`
			Start time.Time `json:"start"`
		} `json:"connections"`
	}
	if err := mihomoGET(api, secret, "/connections", &body); err != nil {
		return flows, ips, err
	}

	seen := map[string]bool{}
	for _, c := range body.Connections {
		m := c.Metadata
		if m.Network != "udp" || !strings.HasPrefix(m.DestinationIP, "31.94.76.") {
			continue
		}
		client := m.SourceIP + ":" + m.SourcePort
		dest := m.DestinationIP + ":" + m.DestinationPort
		if seen[client+"|"+dest] {
			continue
		}
		seen[client+"|"+dest] = true
		flows = append(flows, sessionInfo{Client: client, Dest: dest, LastSeen: int(time.Since(c.Start).Seconds())})
		if !contains(ips, m.DestinationIP) {
			ips = append(ips, m.DestinationIP)
		}
	}
	sort.Slice(flows, func(i, j int) bool { return flows[i].Client < flows[j].Client })
	sort.Strings(ips)
	return flows, ips, nil
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// mihomoDelay asks mihomo to fetch delayURL through the proxy and returns the
// measured round trip. This exercises the same path the ePDG flow uses.
func mihomoDelay(api, secret string) (int64, error) {
	q := url.Values{"timeout": {"5000"}, "url": {delayURL}}
	var out struct {
		Delay int64 `json:"delay"`
	}
	path := "/proxies/" + url.PathEscape(mihomoProxy) + "/delay?" + q.Encode()
	if err := mihomoGET(api, secret, path, &out); err != nil {
		return 0, err
	}
	if out.Delay <= 0 {
		return 0, errors.New("mihomo 没有返回延迟")
	}
	return out.Delay, nil
}

func mihomoGET(api, secret, path string, out any) error {
	if api == "" {
		return errors.New("mihomo_api 未配置")
	}
	req, err := http.NewRequest(http.MethodGet, strings.TrimRight(api, "/")+path, nil)
	if err != nil {
		return err
	}
	if secret != "" {
		req.Header.Set("Authorization", "Bearer "+secret)
	}
	resp, err := (&http.Client{Timeout: 6 * time.Second}).Do(req)
	if err != nil {
		return fmt.Errorf("mihomo: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		msg, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
		return fmt.Errorf("mihomo: %s: %s", resp.Status, strings.TrimSpace(string(msg)))
	}
	return json.NewDecoder(io.LimitReader(resp.Body, 1<<20)).Decode(out)
}
